const ICON_MAP = Object.fromEntries(ICON_SET.map(({ name, Icon }) => [name, Icon]));

export const DEFAULT_ICON_COLOR = "#94a3b8";

export function parseRockIcon(str) {
  if (!str || !str.includes("|")) return { name: null, color: DEFAULT_ICON_COLOR };
  const idx = str.indexOf("|");
  return { name: str.slice(0, idx), color: str.slice(idx + 1) || DEFAULT_ICON_COLOR };
}

export function serializeRockIcon(name, color) {
  return name ? `${name}|${color}` : null;
}

export function RockIconDisplay({ iconStr, size = 16, fallbackColor = "#94a3b8" }) {
  const { name, color } = parseRockIcon(iconStr);
  const Icon = name ? ICON_MAP[name] : null;
  if (!Icon) {
    return (
      <svg width={size} height={size} viewBox="0 0 20 20" fill={fallbackColor}>
        <path fillRule="evenodd" d="M10.868 2.884c-.321-.772-1.415-.772-1.736 0l-1.83 4.401-4.753.381c-.833.067-1.171 1.107-.536 1.651l3.62 3.102-1.106 4.637c-.194.813.691 1.456 1.405 1.02L10 15.591l4.069 2.485c.713.436 1.598-.207 1.404-1.02l-1.106-4.637 3.62-3.102c.635-.544.297-1.584-.536-1.65l-4.752-.382-1.831-4.401z" clipRule="evenodd" />
      </svg>
    );
  }
  return <Icon size={size} color={color} />;
}
